"""Build the blog: posts/*.md -> blog/<slug>/index.html, blog/index.html, blog/feed.xml.

Also refreshes the homepage's Writing list (and its "Latest" line) between marker comments.

    uv run build.py                    # build into the repo; commit the result
    uv run build.py --preview /tmp/x   # whole site incl. drafts/ into another folder

A post is Markdown with a small front matter block:

    ---
    title: Why robots need their own experience
    date: 2026-11-02            (or 2026-11 when only the month is known)
    description: One or two sentences for the index, the homepage and link previews.
    external: https://...       (optional: list a post published elsewhere instead)
    where: Argon Robotics       (optional, with external: where it was published)
    ---

Images go in a folder named after the post (posts/<slug>/fig.png) and are referenced as ![..](fig.png).
Drafts live in drafts/, which git ignores; they are only built with --preview.
"""

from __future__ import annotations

import argparse
import html
import logging
import math
import re
import shutil
import sys
from dataclasses import dataclass
from datetime import date, datetime, time, timezone
from email.utils import format_datetime
from pathlib import Path
from string import Template

import markdown

ROOT = Path(__file__).resolve().parent
SITE_URL = "https://codnay.github.io"
GENERATED = "<!-- generated by build.py from posts/; edit the Markdown, not this file -->"
HOMEPAGE_LIST_LIMIT = 5
WORDS_PER_MINUTE = 230
STATIC_IGNORE = shutil.ignore_patterns(".git", "posts", "drafts", "templates", "blog", "build.py", "README.md", ".gitignore")

log = logging.getLogger("build")


class SiteError(Exception):
    """A post or template is malformed; the message names the file."""


@dataclass(frozen=True)
class Post:
    slug: str
    title: str
    published: date
    month_only: bool
    description: str
    body_md: str
    source_dir: Path
    external: str | None = None
    where: str | None = None

    @property
    def url(self) -> str:
        return self.external or f"{SITE_URL}/blog/{self.slug}/"


# ---------- loading ----------

def parse_front_matter(text: str, path: Path) -> tuple[dict[str, str], str]:
    match = re.match(r"---\n(.*?)\n---\n?(.*)", text, re.S)
    if not match:
        raise SiteError(f"{path.name}: missing the --- front matter block at the top")
    fields = {}
    for line in match.group(1).splitlines():
        if not line.strip():
            continue
        key, sep, value = line.partition(":")
        if not sep:
            raise SiteError(f"{path.name}: front matter line is not 'key: value': {line!r}")
        fields[key.strip()] = value.strip().strip("\"'")
    return fields, match.group(2)


def parse_date(value: str, path: Path) -> tuple[date, bool]:
    for fmt, month_only in (("%Y-%m-%d", False), ("%Y-%m", True)):
        try:
            return datetime.strptime(value, fmt).date(), month_only
        except ValueError:
            continue
    raise SiteError(f"{path.name}: date must be YYYY-MM-DD or YYYY-MM, got {value!r}")


def load_post(path: Path) -> Post:
    fields, body = parse_front_matter(path.read_text(encoding="utf-8"), path)
    missing = [k for k in ("title", "date", "description") if not fields.get(k)]
    if missing:
        raise SiteError(f"{path.name}: front matter is missing {', '.join(missing)}")
    if not fields.get("external") and not body.strip():
        raise SiteError(f"{path.name}: no body and no external link")
    published, month_only = parse_date(fields["date"], path)
    return Post(
        slug=path.stem, title=fields["title"], published=published, month_only=month_only,
        description=fields["description"], body_md=body, source_dir=path.with_suffix(""),
        external=fields.get("external") or None, where=fields.get("where") or None,
    )


def load_posts(folders: list[Path]) -> list[Post]:
    posts = [load_post(p) for folder in folders if folder.is_dir() for p in sorted(folder.glob("*.md"))]
    slugs = [p.slug for p in posts]
    dupes = {s for s in slugs if slugs.count(s) > 1}
    if dupes:
        raise SiteError(f"two posts share a file name: {', '.join(sorted(dupes))}")
    return sorted(posts, key=lambda p: (p.published, p.slug), reverse=True)


# ---------- formatting ----------

def esc(text: str) -> str:
    return html.escape(text, quote=True)


def long_date(post: Post) -> str:
    return post.published.strftime("%B %Y" if post.month_only else "%B %-d, %Y")


def short_date(post: Post) -> str:
    return post.published.strftime("%b" if post.month_only else "%b %-d")


def read_minutes(body_md: str) -> int:
    return max(1, math.ceil(len(re.findall(r"\w+", body_md)) / WORDS_PER_MINUTE))


def render_markdown(body_md: str) -> str:
    md = markdown.Markdown(
        extensions=["extra", "smarty", "sane_lists", "toc"],
        extension_configs={"toc": {"permalink": "#", "permalink_title": "Link to this section"}},
    )
    return md.convert(body_md)


def load_template(name: str) -> Template:
    return Template((ROOT / "templates" / name).read_text(encoding="utf-8"))


def page(content: str, *, title: str, description: str, canonical: str, root: str, blog_current: bool,
         og_type: str = "website") -> str:
    return load_template("base.html").substitute(
        title=esc(title), og_title=esc(title), description=esc(description), canonical=canonical,
        site_url=SITE_URL, root=root, og_type=og_type, content=content,
        blog_current=' aria-current="page"' if blog_current else "",
    ).replace("<head>", f"<head>\n{GENERATED}", 1)


# ---------- pages ----------

def render_post(post: Post) -> str:
    dek = f'\n      <p class="dek">{esc(post.description)}</p>' if post.description else ""
    content = load_template("post.html").substitute(
        title=esc(post.title), date_iso=post.published.isoformat(), date_long=long_date(post),
        read_time=read_minutes(post.body_md), dek=dek, body=render_markdown(post.body_md),
    )
    return page(content, title=f"{post.title} · Pranay Gupta", description=post.description,
                canonical=post.url, root="../../", blog_current=True, og_type="article")


def index_item(post: Post, show_year: bool, href: str) -> str:
    year = post.published.year if show_year else ""
    if post.external:
        meta = f"{short_date(post)} · {esc(post.where or 'elsewhere')} ↗"
    else:
        meta = f"{short_date(post)} · {read_minutes(post.body_md)} min read"
    return (
        f'      <li>\n        <span class="year">{year}</span>\n        <div class="item">\n'
        f'          <a class="item-title" href="{esc(href)}">{esc(post.title)}</a>\n'
        f'          <span class="item-sub">{esc(post.description)}</span>\n'
        f'          <span class="where">{meta}</span>\n        </div>\n      </li>'
    )


def render_index(posts: list[Post]) -> str:
    items, last_year = [], None
    for post in posts:
        href = post.external or f"{post.slug}/"
        items.append(index_item(post, post.published.year != last_year, href))
        last_year = post.published.year
    content = load_template("blog.html").substitute(items="\n".join(items))
    return page(content, title="Blog · Pranay Gupta", canonical=f"{SITE_URL}/blog/", root="../", blog_current=True,
                description="Pranay Gupta's notes on robot learning, simulation and RL post-training.")


def render_feed(posts: list[Post]) -> str:
    items = []
    for post in posts:
        stamp = format_datetime(datetime.combine(post.published, time(12), tzinfo=timezone.utc))
        body = "" if post.external else f"\n      <content:encoded><![CDATA[{render_markdown(post.body_md)}]]></content:encoded>"
        items.append(
            f"    <item>\n      <title>{esc(post.title)}</title>\n      <link>{esc(post.url)}</link>\n"
            f"      <guid>{esc(post.url)}</guid>\n      <pubDate>{stamp}</pubDate>\n"
            f"      <description>{esc(post.description)}</description>{body}\n    </item>"
        )
    return (
        '<?xml version="1.0" encoding="UTF-8"?>\n'
        '<rss version="2.0" xmlns:content="http://purl.org/rss/1.0/modules/content/">\n  <channel>\n'
        f"    <title>Pranay Gupta</title>\n    <link>{SITE_URL}/blog/</link>\n"
        "    <description>Notes on robot learning, simulation and RL post-training.</description>\n"
        "    <language>en</language>\n" + "\n".join(items) + "\n  </channel>\n</rss>\n"
    )


# ---------- homepage ----------

def replace_between(text: str, name: str, new: str) -> str:
    pattern = re.compile(rf"(<!-- {name}:start -->).*?([ \t]*<!-- {name}:end -->)", re.S)
    if not pattern.search(text):
        raise SiteError(f"index.html: markers <!-- {name}:start/end --> not found")
    return pattern.sub(lambda m: f"{m.group(1)}\n{new}\n{m.group(2)}", text, count=1)


def update_homepage(homepage: Path, posts: list[Post]) -> None:
    text = homepage.read_text(encoding="utf-8")
    items, last_year = [], None
    for post in posts[:HOMEPAGE_LIST_LIMIT]:
        items.append(index_item(post, post.published.year != last_year, post.external or f"blog/{post.slug}/"))
        last_year = post.published.year
    text = replace_between(text, "writing", "\n".join(items))
    own = [p for p in posts if not p.external]
    if own:  # "Latest" promotes your own writing; until there is some it keeps its hand-written text
        latest = f'      <p class="latest">Latest: {esc(own[0].title)}. <a href="blog/{own[0].slug}/">Read the post →</a></p>'
        text = replace_between(text, "latest", latest)
    homepage.write_text(text, encoding="utf-8")


# ---------- output ----------

def remove_stale(blog_dir: Path, keep: set[str]) -> None:
    for child in blog_dir.iterdir():
        page_file = child / "index.html"
        if child.is_dir() and child.name not in keep and page_file.exists() and GENERATED in page_file.read_text():
            log.info("removing %s (its post is gone)", child.relative_to(blog_dir.parent))
            shutil.rmtree(child)


def write_post(post: Post, blog_dir: Path) -> None:
    out = blog_dir / post.slug
    out.mkdir(parents=True, exist_ok=True)
    (out / "index.html").write_text(render_post(post), encoding="utf-8")
    if post.source_dir.is_dir():
        shutil.copytree(post.source_dir, out, dirs_exist_ok=True)


def build(site_dir: Path, include_drafts: bool) -> list[Post]:
    folders = [ROOT / "posts"] + ([ROOT / "drafts"] if include_drafts else [])
    posts = load_posts(folders)
    blog_dir = site_dir / "blog"
    blog_dir.mkdir(exist_ok=True)
    own = [p for p in posts if not p.external]
    remove_stale(blog_dir, {p.slug for p in own})
    for post in own:
        write_post(post, blog_dir)
    (blog_dir / "index.html").write_text(render_index(posts), encoding="utf-8")
    (blog_dir / "feed.xml").write_text(render_feed(posts), encoding="utf-8")
    update_homepage(site_dir / "index.html", posts)
    return posts


def main() -> int:
    logging.basicConfig(level=logging.INFO, format="%(message)s")
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--preview", type=Path, metavar="DIR",
                        help="build the whole site, drafts included, into DIR instead of the repo")
    args = parser.parse_args()
    site_dir = ROOT
    if args.preview:
        site_dir = args.preview.resolve()
        if site_dir == ROOT or ROOT in site_dir.parents:
            parser.error("--preview must be outside the repo, so drafts never land in a commit")
        shutil.copytree(ROOT, site_dir, ignore=STATIC_IGNORE, dirs_exist_ok=True)
    try:
        posts = build(site_dir, include_drafts=bool(args.preview))
    except SiteError as err:
        log.error("build failed: %s", err)
        return 1
    own = sum(1 for p in posts if not p.external)
    log.info("built %d posts (%d here, %d linked elsewhere) into %s", len(posts), own, len(posts) - own, site_dir)
    return 0


if __name__ == "__main__":
    sys.exit(main())
